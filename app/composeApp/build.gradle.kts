// --- Version and update key -----------------------------------------------------------------
// The next version to be released is in VERSION (repository root). release.yml sets
// GHUL_VERSION: "0.6.0" for a release from main, "0.6.0-dev.12" for a development version from
// dev. Local builds and the test versions of pull requests are "<VERSION>-dev".
// GHUL_UPDATE_KEY is the public half of the signing key (PEM). Without it (local builds, F-Droid,
// forks) the app does not update itself. Neither is a secret.
val baseVersion = rootProject.layout.projectDirectory.file("../VERSION").asFile.readText().trim()
val versionPattern = Regex("""(\d+)\.(\d+)\.(\d+)(-[0-9A-Za-z]+(\.[0-9A-Za-z]+)*)?""")
val appVersion = System.getenv("GHUL_VERSION")?.takeIf { versionPattern.matches(it) } ?: "$baseVersion-dev"
// Running number within a version: development versions 0..98 ("-dev.12" -> 12), the release 99.
// So every version is higher than the one before, a release higher than all its development
// versions, and the system installers accept each as an update.
val versionParts = versionPattern.matchEntire(appVersion)!!.groupValues
val versionStep = versionParts[4].removePrefix("-").let { pre ->
    if (pre.isEmpty()) 99 else (pre.substringAfterLast('.').toIntOrNull() ?: 0).coerceAtMost(98)
}
// Android: 0.6.0 -> 60099, 0.6.0-dev.12 -> 60012.
val appVersionCode = ((versionParts[1].toInt() * 100 + versionParts[2].toInt()) * 100 + versionParts[3].toInt()) * 100 + versionStep
// Windows installer (only three numbers, the third up to 65535): 0.6.0 -> 0.6.99, 0.6.0-dev.12 -> 0.6.12.
val msiVersion = "${versionParts[1]}.${versionParts[2]}.${versionParts[3].toInt() * 100 + versionStep}"
val updateKey = System.getenv("GHUL_UPDATE_KEY").orEmpty().trim()
val buildInfoOut = layout.buildDirectory.dir("generated/buildinfo/kotlin")
val generateBuildInfo by tasks.registering {
    group = "build"
    description = "Writes the version and the public update key into BuildInfo.kt."
    inputs.property("version", appVersion)
    inputs.property("updateKey", updateKey)
    outputs.dir(buildInfoOut)
    doLast {
        val q = "\"\"\""
        val file = buildInfoOut.get().file("de/danerd/ghulsuite/BuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "// Generated by build.gradle.kts\npackage de.danerd.ghulsuite\n\n" +
                "object BuildInfo {\n" +
                "    const val VERSION = \"$appVersion\"\n" +
                "    const val UPDATE_REPO = \"ghulaschsuppe/GhulSuite\"\n" +
                "    const val UPDATE_KEY = $q$updateKey$q\n" +
                "}\n",
        )
    }
}

